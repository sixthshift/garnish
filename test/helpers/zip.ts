// Building a zip in memory, so the import's tests (M34.3) have an archive to
// read without a fixture binary in the repo. The archive is the app's own
// writer's (src/lib/zip.ts); `deflate` is the tests' older name for `compress`.
import { writeZip } from "../../src/lib/zip";

export type ZipInput = { name: string; bytes: Uint8Array; deflate?: boolean };

/** The files as a zip archive. */
export function makeZip(files: readonly ZipInput[]): Promise<Uint8Array> {
  return writeZip(files.map((file) => ({ name: file.name, bytes: file.bytes, compress: file.deflate })));
}

